use std::fs;
use std::io::Write;
use std::path::PathBuf;

use gitpulse_lib::error::AppError;
use gitpulse_lib::models::*;
use ts_rs::TS;

fn main() -> Result<(), Box<dyn std::error::Error>> {
    let config = ts_rs::Config::default();
    let declarations = vec![
        ErrorCode::decl(&config),
        PrimaryStatus::decl(&config),
        WatcherState::decl(&config),
        ChangeCounts::decl(&config),
        RepoFlags::decl(&config),
        LastCommit::decl(&config),
        RepoSummary::decl(&config),
        FileStatus::decl(&config),
        FileChange::decl(&config),
        ChangeList::decl(&config),
        FileDiff::decl(&config),
        CommitEntry::decl(&config),
        CommitPage::decl(&config),
        BranchEntry::decl(&config),
        ActivityEntry::decl(&config),
        ScanCandidate::decl(&config),
        ScanHandle::decl(&config),
        ScanCompleted::decl(&config),
        AddRepoResult::decl(&config),
        AddReposResult::decl(&config),
        TrayStats::decl(&config),
        Theme::decl(&config),
        ShowDockIcon::decl(&config),
        TrayBadgeBasis::decl(&config),
        WatchMode::decl(&config),
        RefreshModeArg::decl(&config),
        NotificationSettings::decl(&config),
        Settings::decl(&config),
        ScanProgress::decl(&config),
        SettingsPatch::decl(&config),
        ExportResult::decl(&config),
        AppError::decl(&config),
    ];

    let target = PathBuf::from("src/lib/bindings.generated.ts");
    if let Some(parent) = target.parent() {
        fs::create_dir_all(parent)?;
    }
    let mut file = fs::File::create(&target)?;
    writeln!(
        file,
        "// Generated by `cargo run --bin export_bindings`. Do not edit by hand."
    )?;
    writeln!(
        file,
        "// Run `pnpm gen:bindings` after changing Rust models.\n"
    )?;
    for declaration in declarations {
        writeln!(file, "export {declaration}\n")?;
    }
    println!("wrote {}", target.display());
    Ok(())
}
